"""Render HOL Light proof exports as data for the ordinary MeTTa checker.

This module does not check HOL proofs. The generated program checks the
received inference requests and their claimed conclusions in MeTTa.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterable

from hol_light_prepare_export_v1 import group_type_definitions


LIBRARY = ("data", "syntax", "kernel", "definitions", "derived", "profile", "receive")
SOURCE_REVISION = "924faf0c3471a04174ffdeb8576ce7cabcb92d64"


def call(head: str, *arguments: str) -> str:
    return "(" + " ".join((head, *arguments)) + ")"


def string(value: str) -> str:
    if not isinstance(value, str):
        raise ValueError("an object-language name must be a string")
    return json.dumps(value, ensure_ascii=False)


def tagged(values: Iterable[str]) -> str:
    items = list(values)
    return "".join("(HOL:Cons " + value + " " for value in items) + "HOL:Nil" + ")" * len(items)


def source_type(value: list) -> str:
    if len(value) == 2 and value[0] == "var":
        return call("Tyvar", string(value[1]))
    if len(value) == 3 and value[0] == "op" and isinstance(value[2], list):
        return call("Tyapp", string(value[1]), tagged(map(source_type, value[2])))
    raise ValueError("malformed exported HOL type")


def source_term(value: list) -> str:
    if len(value) != 3:
        raise ValueError("malformed exported HOL term")
    tag, first, second = value
    if tag in ("var", "const"):
        return call("Var" if tag == "var" else "Const", string(first), source_type(second))
    if tag in ("app", "abs"):
        return call("Comb" if tag == "app" else "Abs", source_term(first), source_term(second))
    raise ValueError("unknown exported HOL term constructor")


def library_text(repository: Path | None = None) -> str:
    root = repository or Path(__file__).resolve().parents[1]
    return "\n".join((root / "lib" / "hol_light" / (name + ".metta")).read_text()
                     for name in LIBRARY)


def expected(theorem: dict) -> tuple[str, str]:
    return tagged(map(source_term, theorem["hypotheses"])), source_term(theorem["conclusion"])


def profile_text(standard: dict) -> str:
    if standard["sourceRevision"] != SOURCE_REVISION:
        raise ValueError("standard theory belongs to a different pinned source revision")
    definitions = []
    for node in standard["definitions"]:
        equation, name, schema = node["arguments"]
        definitions.append(call("HOL:Step", string("standard-definition:" + name),
                                call("DEFINITION", string(name), source_type(schema),
                                     source_term(equation[2]))))
    commitments = [call("HOL:Entry", string(name), source_term(theorem["conclusion"]))
                   for name, theorem in zip(("ETA_AX", "SELECT_AX", "INFINITY_AX"),
                                            standard["commitments"], strict=True)]
    return ("; Generated by tools/hol_light_petta_v1.py from the pinned source-theory export.\n"
            "; Profile selection is explicit; used commitments remain in each theorem.\n\n" +
            call("=", call("hol-light:source-revision"), string(SOURCE_REVISION)) + "\n\n" +
            call("=", call("hol-light:standard-definitions"), call("quote", tagged(definitions))) + "\n\n" +
            call("=", call("hol-light:standard-commitments"), call("quote", tagged(commitments))) + "\n\n" +
            "(= (hol-light:standard-run $commands)\n"
            "  (let $commitments (hol-light:standard-commitments)\n"
            "    (let $definitions (hol-light:standard-definitions)\n"
            "      (let $all (hol-light:append $definitions $commands)\n"
            "        (hol-light:run $commitments $all)))))\n")


def source_key(identifier: int) -> str:
    if type(identifier) is not int or identifier < 0:
        raise ValueError("source proof ids must be non-negative integers")
    return call("HOL:Source", str(identifier))


def export_events(nodes: Iterable[dict], standard: dict) -> tuple[list[str], dict[int, str]]:
    """Use only earlier proof ids; do not unfold shared proof dependencies.

    The standard Boolean definitions are installed by standard-run. Their
    exported results are reused by an empty INST, then compared with the
    exported statement by the receiving MeTTa program. Every other event is
    replayed through its kernel request, including both type-definition laws.
    """
    if standard["sourceRevision"] != SOURCE_REVISION:
        raise ValueError("export adapter and standard theory have different source revisions")
    standard_definitions = {node["arguments"][1] for node in standard["definitions"]}
    commitments = {json.dumps(theorem["conclusion"], sort_keys=True): name
                   for name, theorem in zip(("ETA_AX", "SELECT_AX", "INFINITY_AX"),
                                            standard["commitments"], strict=True)}
    keys: dict[int, str] = {}
    events: list[str] = []

    def premise(identifier: int) -> str:
        if identifier not in keys:
            raise ValueError(f"proof {identifier} has not been received yet")
        return keys[identifier]

    for node in group_type_definitions(nodes):
        identifier, rule, arguments = node["id"], node["rule"], node["arguments"]
        if identifier in keys:
            raise ValueError(f"duplicate source proof id {identifier}")
        key = source_key(identifier)
        if rule in ("REFL", "BETA", "ASSUME"):
            request = call(rule, source_term(arguments[0]))
        elif rule in ("TRANS", "MK_COMB", "EQ_MP", "DEDUCT_ANTISYM_RULE"):
            request = call(rule, premise(arguments[0]), premise(arguments[1]))
        elif rule == "ABS":
            request = call(rule, source_term(arguments[1]), premise(arguments[0]))
        elif rule in ("INST", "INST_TYPE"):
            convert = source_term if rule == "INST" else source_type
            pairs = tagged(call("HOL:Maplet", convert(replacement), convert(variable))
                           for replacement, variable in arguments[1])
            request = call(rule, pairs, premise(arguments[0]))
        elif rule == "DEFINITION":
            equation, name, schema = arguments
            if equation[0] != "app" or equation[1][0] != "app":
                raise ValueError("a constant definition must return an equation")
            if name in standard_definitions:
                request = call("DEFINITION", string(name), source_type(schema),
                               source_term(equation[2]))
                hypotheses, conclusion = expected(node["theorem"])
                events.append(call("HOL:CheckedReuse", key, request,
                                   string("standard-definition:" + name), hypotheses, conclusion))
                keys[identifier] = key
                continue
            else:
                request = call(rule, string(name), source_type(schema), source_term(equation[2]))
        elif rule == "AXIOM":
            name = commitments.get(json.dumps(arguments[0], sort_keys=True), "UNDECLARED")
            request = call(rule, string(name), source_term(arguments[0]))
        elif rule == "TYPE_DEFINITION_PAIR":
            existence, name, abstraction, representation = arguments
            request = call("TYPE_DEFINITION", string(name), string(abstraction),
                           string(representation), premise(existence))
            mate = node["mate"]
            if mate in keys or mate == identifier:
                raise ValueError("duplicate type-definition result id")
            first_hyps, first_conclusion = expected(node["theorems"][0])
            second_hyps, second_conclusion = expected(node["theorems"][1])
            events.append(call("HOL:CheckedType", key, request, first_hyps, first_conclusion,
                               second_hyps, second_conclusion))
            keys[identifier], keys[mate] = key, call("HOL:RepKey", key)
            continue
        else:
            raise ValueError(f"unsupported HOL Light source rule {rule}")
        hypotheses, conclusion = expected(node["theorem"])
        events.append(call("HOL:CheckedStep", key, request, hypotheses, conclusion))
        keys[identifier] = key
    return events, keys


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, help="write a self-contained MeTTa library")
    parser.add_argument("--example", type=Path, help="append a library example to --bundle")
    parser.add_argument("--nodes", type=Path, help="HOL Light proof-node JSONL")
    parser.add_argument("--standard", type=Path, help="pinned standard-theory JSON")
    parser.add_argument("--output", type=Path, help="write a self-contained receiving program")
    parser.add_argument("--root", type=int, help="check this received proof id")
    parser.add_argument("--profile-output", type=Path, help="regenerate profile.metta from --standard")
    args = parser.parse_args()
    if args.bundle is not None:
        example = ""
        if args.example is not None:
            for line in args.example.read_text().splitlines(keepends=True):
                if line.startswith("!(import! "):
                    if line.strip() not in {f"!(import! &self ../../lib/hol_light/{name}.metta)"
                                           for name in LIBRARY}:
                        parser.error("example contains an import outside the bundled library")
                else:
                    example += line
        args.bundle.write_text("; Generated standalone library and example.\n" + library_text() +
                               "\n" + example)
    elif args.example is not None:
        parser.error("--example requires --bundle")
    if args.profile_output is not None:
        if args.standard is None:
            parser.error("--profile-output requires --standard")
        args.profile_output.write_text(profile_text(json.loads(args.standard.read_text())))
    if args.nodes is not None:
        if args.standard is None or args.output is None or args.root is None:
            parser.error("--nodes requires --standard, --output and --root")
        standard = json.loads(args.standard.read_text())
        with args.nodes.open() as stream:
            nodes = [json.loads(line) for line in stream if line.strip()]
        events, keys = export_events(nodes, standard)
        if args.root not in keys:
            parser.error("the requested root is not in this closure")
        body = call("let", "$events", call("export:events"),
                    call("let", "$result", call("hol-light:standard-receive", "$events"),
                         call("HOL:Received", keys[args.root],
                              call("hol-light:accepted", "$result"),
                              call("hol-light:receipt-count", "$result"),
                              call("hol-light:dependencies", "$result", keys[args.root]))))
        args.output.write_text(library_text() + "\n" +
                               call("=", call("export:events"), call("quote", tagged(events))) +
                               "\n!" + body + "\n")
        print(json.dumps({"source_results": len(keys), "checked_events": len(events),
                          "proof_checking": "generated MeTTa program"}))
    elif args.bundle is None and args.profile_output is None:
        parser.error("select --bundle or --nodes")


if __name__ == "__main__":
    main()
