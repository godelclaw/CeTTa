#!/usr/bin/env python3
"""Write the tables str:python-lower uses: CPython 3.12's str.lower, Unicode 15.0.0.

str.lower maps every code point through its full lowercase mapping (one code
point may become several) except U+03A3 GREEK CAPITAL LETTER SIGMA, which
becomes final sigma U+03C2 in the Final_Sigma context and U+03C3 otherwise.
That context reads two character properties, case-ignorable and cased, which
Python does not expose. They are recovered from how Python lowers a sigma
after the code point: c is case-ignorable when "A" + c + "Σ" ends in
final sigma but c + "Σ" does not, and c ends a scan as cased when
c + "Σ" ends in final sigma. Every value is read from the running Python,
so run this with the Python whose str.lower the tables must match; any other
Unicode version is refused. The tables are checked against str.lower on
generated sigma contexts before they are written.
"""
import argparse
import random
import sys
import unicodedata
from pathlib import Path

VERSION = "15.0.0"
SIGMA = 0x03A3


def mappings():
    rows = []
    for code in range(0x110000):
        if code == SIGMA:
            continue
        lowered = chr(code).lower()
        if lowered != chr(code):
            rows.append((code, [ord(c) for c in lowered]))
    return rows


def properties():
    ignorable, cased = [], []
    for code in range(0x110000):
        c = chr(code)
        after_letter = ("A" + c + "Σ").lower().endswith("ς")
        alone = (c + "Σ").lower().endswith("ς")
        ignorable.append(after_letter and not alone)
        cased.append(alone)
    return ignorable, cased


def toggles(flags):
    """The code points where a property switches, starting off at U+0000."""
    starts, previous = [], False
    for code, flag in enumerate(flags):
        if flag != previous:
            starts.append(code)
            previous = flag
    return starts


def lower(codes, table, ignorable, cased):
    """str.lower as the native computes it, for the self-check."""
    out = []
    for i, code in enumerate(codes):
        if code != SIGMA:
            out.extend(table.get(code, [code]))
            continue
        j = i - 1
        while j >= 0 and ignorable[codes[j]]:
            j -= 1
        final = j >= 0 and cased[codes[j]]
        if final and i + 1 < len(codes):
            j = i + 1
            while j < len(codes) and ignorable[codes[j]]:
                j += 1
            final = j == len(codes) or not cased[codes[j]]
        out.append(0x03C2 if final else 0x03C3)
    return out


def check(table, ignorable, cased):
    pool = ([SIGMA, 0x03C3, 0x03C2, 0x41, 0x61, 0x20, 0x27, 0x2E, 0x31, 0x0130, 0x1F88, 0x02B0, 0x00AD, 0x0345]
            + [code for code in range(0x300, 0x370)] + [0xD800, 0xDFFF, 0x10400, 0xE0001])
    pool += [code for code, flag in enumerate(ignorable) if flag][::97]
    pool += [code for code, flag in enumerate(cased) if flag][::97]
    generator = random.Random(15)
    for _ in range(200000):
        codes = [generator.choice(pool) for _ in range(generator.randrange(1, 9))]
        text = "".join(map(chr, codes))
        if lower(codes, table, ignorable, cased) != [ord(c) for c in text.lower()]:
            raise SystemExit("self-check failed on %r" % text)


def array(name, kind, values, per_line=12):
    lines = ["static const %s %s[%d] = {" % (kind, name, len(values))]
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(values[start:start + per_line]) + ",")
    lines.append("};")
    return lines


def render(rows, ignorable_starts, cased_starts):
    width = max(len(mapped) for _, mapped in rows)
    lines = [
        "/* Generated by tools/generate_python_lower15.py from CPython 3.12's str.lower",
        " * (Unicode %s); do not edit. Unicode data are covered by" % VERSION,
        " * langdef/unicode/LICENSE.txt (Unicode-3.0). */",
        "#ifndef CETTA_PYTHON_LOWER15_H",
        "#define CETTA_PYTHON_LOWER15_H",
        "",
        "#include <stdint.h>",
        "",
        'static const char cetta_python_lower15_version[] = "%s";' % VERSION,
        "",
        "/* Full lowercase mappings of every code point but U+03A3, by code point. */",
        "#define CETTA_PYTHON_LOWER15_MAPPINGS %du" % len(rows),
        "#define CETTA_PYTHON_LOWER15_WIDTH %du" % width,
    ]
    lines += array("cetta_python_lower15_from", "uint32_t", ["0x%04X" % code for code, _ in rows])
    lines += array("cetta_python_lower15_widths", "uint8_t", [str(len(mapped)) for _, mapped in rows], 24)
    lines += ["static const uint32_t cetta_python_lower15_to[%d][%d] = {" % (len(rows), width)]
    for start in range(0, len(rows), 6):
        lines.append("    " + " ".join(
            "{%s}," % ", ".join("0x%04X" % c for c in mapped + [0] * (width - len(mapped)))
            for _, mapped in rows[start:start + 6]))
    lines += ["};", "",
              "/* The Final_Sigma properties: a code point has one when an odd number of",
              " * its table's starts are at or below it. */",
              "#define CETTA_PYTHON_LOWER15_IGNORABLE_STARTS %du" % len(ignorable_starts)]
    lines += array("cetta_python_lower15_ignorable_starts", "uint32_t", ["0x%04X" % c for c in ignorable_starts])
    lines += ["#define CETTA_PYTHON_LOWER15_CASED_STARTS %du" % len(cased_starts)]
    lines += array("cetta_python_lower15_cased_starts", "uint32_t", ["0x%04X" % c for c in cased_starts])
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true", help="fail when the file differs")
    arguments = parser.parse_args()
    if unicodedata.unidata_version != VERSION:
        if arguments.check:
            print("%s: SKIP, this Python has Unicode %s, not %s" % (arguments.output, unicodedata.unidata_version, VERSION))
            return 0
        raise SystemExit("this Python has Unicode %s; run with Python 3.12 (Unicode %s)"
                         % (unicodedata.unidata_version, VERSION))
    rows = mappings()
    ignorable, cased = properties()
    check(dict(rows), ignorable, cased)
    text = render(rows, toggles(ignorable), toggles(cased))
    if arguments.check:
        if arguments.output.read_text() != text:
            raise SystemExit("%s is out of date" % arguments.output)
        print("%s is up to date" % arguments.output)
    else:
        arguments.output.write_text(text)
        print("wrote %s: %d mappings" % (arguments.output, len(rows)))


if __name__ == "__main__":
    sys.exit(main())
