#!/usr/bin/env python3
"""Generate the native Megalodon primitive inventories from upstream source.

Reads Megalodon's src/syntax.ml (`primname`) and writes
native/megalodon/mg_profile_prims.inc: for every upstream profile tag
(HF, Egal, Mizar, HOAS, SetMM) the exact primitive index, source name and
type, in Megalodon's own -sexprinfo type spelling.  Nothing is invented:
an index the source does not give a profile is not a primitive there.

usage: megalodon_profiles_from_upstream.py SYNTAX_ML OUTPUT [--check]
"""
import hashlib
import re
import sys

PROFILES = ["HF", "Egal", "Mizar", "HOAS", "SetMM"]


def ocaml_type_to_sexpr(text):
    pos = 0

    def parse():
        nonlocal pos
        while text[pos] == " ":
            pos += 1
        for word, out in (("Prop", "(PROP)"), ("Set", "(SET)")):
            if text.startswith(word, pos):
                pos += len(word)
                return out
        if text.startswith("Ar(", pos):
            pos += 3
            a = parse()
            assert text[pos] == ",", text[pos:]
            pos += 1
            b = parse()
            assert text[pos] == ")", text[pos:]
            pos += 1
            return "(AR %s %s)" % (a, b)
        if text.startswith("TpVar ", pos):
            pos += 6
            m = re.match(r"\d+", text[pos:])
            pos += len(m.group(0))
            return "(TPVAR %s)" % m.group(0)
        raise ValueError("cannot parse type at %r" % text[pos:])

    out = parse()
    assert pos == len(text), text
    return out


def extract(source):
    start = source.index("let primname x =")
    end = source.index("type tm =", start)
    body = source[start:end]
    split = body.index("\n  else\n    match x with")
    setmm_part, rest = body[:split], body[split:]
    entries = {p: [] for p in PROFILES}
    row = re.compile(r'\|\s*"([^"]+)"\s*->\s*\((\d+),\((\d+),(.*)\)\)\s*$')
    for line in setmm_part.splitlines():
        m = row.match(line.strip())
        if not m:
            continue
        name, index, tvars, tp = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)
        entries["SetMM"].append((index, name, tvars, ocaml_type_to_sexpr(tp)))
    guarded = re.compile(r'\|\s*"([^"]+)"\s*->\s*if (.*) then (.*) else (.*)$')
    for line in rest.splitlines():
        line = line.strip()
        if line.startswith("(*"):
            continue
        m = guarded.match(line)
        if not m:
            continue
        name, cond, then_, else_ = m.groups()
        def parse_result(r):
            r = r.strip()
            if r == "raise Not_found":
                return None
            mm = re.match(r"\((\d+),\((\d+),(.*)\)\)$", r)
            return int(mm.group(1)), int(mm.group(2)), ocaml_type_to_sexpr(mm.group(3))
        tests = re.findall(r"!pfgtheory = (\w+)", cond)
        for profile in ["HF", "Egal", "Mizar", "HOAS"]:
            holds = profile in tests
            if " || " not in cond and len(tests) == 1:
                holds = profile == tests[0]
            result = parse_result(then_ if holds else else_)
            if result:
                entries[profile].append((result[0], name, result[1], result[2]))
    for p in PROFILES:
        entries[p].sort()
    return entries


def render(entries, source_hash):
    out = ["/* Generated by tools/megalodon_profiles_from_upstream.py from",
           " * megalodon-upstream/src/syntax.ml (primname), SHA-256",
           " * %s." % source_hash,
           " * Do not edit.  Rows: { Prim index, source name, type variables,",
           " * type in Megalodon -sexprinfo spelling }. */", ""]
    for p in PROFILES:
        out.append("static const MgPrimSpec mg_prims_%s[] = {" % p.lower())
        for index, name, tvars, tp in entries[p]:
            out.append('    {%d, "%s", %d, "%s"},' % (index, name, tvars, tp))
        if not entries[p]:
            out.append("    {0, NULL, 0, NULL},")
        out.append("};")
        out.append("#define MG_PRIMS_%s_COUNT %du" % (p.upper(), len(entries[p])))
        out.append("")
    return "\n".join(out)


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    data = open(args[0], "rb").read()
    text = render(extract(data.decode("utf-8", "replace")), hashlib.sha256(data).hexdigest())
    if "--check" in argv:
        current = open(args[1]).read()
        if current != text:
            print("%s is out of date" % args[1], file=sys.stderr)
            return 1
        print("%s is up to date" % args[1])
        return 0
    open(args[1], "w").write(text)
    print("wrote %s" % args[1])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
