#!/usr/bin/env python3
"""Write the Unicode 15.0.0 General_Category table str:unicode-category uses.

The categories are those Python 3.12's unicodedata reports for every code
point from U+0000 to U+10FFFF, unassigned (Cn), surrogate (Cs) and private use
(Co) code points included. The table keeps one row per run of code points
sharing a category. Run with the Python whose unicodedata the table must
match; any other Unicode version is refused.
"""
import argparse
import sys
import unicodedata
from pathlib import Path

VERSION = "15.0.0"
CATEGORIES = ("Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po "
              "Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co Cn").split()


def runs():
    previous = None
    for code in range(0x110000):
        category = unicodedata.category(chr(code))
        if category != previous:
            yield code, CATEGORIES.index(category)
            previous = category


def render(table):
    lines = [
        "/* Generated by tools/generate_unicode_category15.py from Python's unicodedata",
        " * (Unicode %s); do not edit. Unicode data are covered by" % VERSION,
        " * langdef/unicode/LICENSE.txt (Unicode-3.0). */",
        "#ifndef CETTA_UNICODE_CATEGORY15_H",
        "#define CETTA_UNICODE_CATEGORY15_H",
        "",
        "#include <stdint.h>",
        "",
        'static const char cetta_unicode_category15_version[] = "%s";' % VERSION,
        "static const char cetta_unicode_category15_names[%d][3] = {" % len(CATEGORIES),
        "    " + ", ".join('"%s"' % name for name in CATEGORIES) + "};",
        "",
        "/* A run starts at its code point and lasts until the next run starts. */",
        "#define CETTA_UNICODE_CATEGORY15_RUNS %du" % len(table),
        "static const uint32_t cetta_unicode_category15_starts[CETTA_UNICODE_CATEGORY15_RUNS] = {",
    ]
    for at in range(0, len(table), 8):
        lines.append("    " + ", ".join("0x%05x" % code for code, _ in table[at:at + 8]) + ",")
    lines.append("};")
    lines.append("static const uint8_t cetta_unicode_category15_values[CETTA_UNICODE_CATEGORY15_RUNS] = {")
    for at in range(0, len(table), 16):
        lines.append("    " + ", ".join("%d" % value for _, value in table[at:at + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1]
                        / "src" / "unicode_category15.h")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if unicodedata.unidata_version != VERSION:
        raise SystemExit("unicodedata holds Unicode %s; the table needs %s (Python 3.12)"
                         % (unicodedata.unidata_version, VERSION))
    text = render(list(runs()))
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            raise SystemExit("stale: %s" % args.output)
        return 0
    args.output.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
